suite "inflate":
  test "stored, fixed and dynamic blocks":
    check unzlib(unhex(storedZ)) == "abc"
    check unzlib(unhex(fixedZ)) == "abcabcabc"
    check unzlib(unhex(dynamicZ)) == original()

  test "gzip":
    # gzip.compress(b"abcabcabc", mtime=0)
    check ungzip(unhex("1f8b08000000000002034b4c4a4e04230018482d4609000000")) == "abcabcabc"

  test "bad data":
    expect InflateError: discard unzlib("")
    expect InflateError: discard unzlib("xx not zlib at all")
    expect InflateError: discard unzlib(unhex(dynamicZ)[0 .. 40])
    expect InflateError: discard unzlib(unhex(dynamicZ), 100)
    expect InflateError: discard ungzip("not gzip, not even close")
