proc unhex(s: string): string =
  for i in 0 ..< s.len div 2: result.add char(parseHexInt(s[2 * i .. 2 * i + 1]))

proc original(): string =
  for i in 0 ..< 3000: result.add char((i * i div 7) mod 251)
  result.add "hello hello hello ".repeat(50)

