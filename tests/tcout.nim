import std/[os, osproc, strutils, unittest]
import batchpad/[asmout, cout, ctm, rawbin, spd]

proc charProject(mode = dmMulticolourText, colouring = cmPerTile): ctm.Project =
  result = ctm.Project(version: 9, displayMode: mode, colouring: colouring,
                       tileSystem: true, tileWidth: 2, tileHeight: 1,
                       chipColours: [6'u8, 11, 12, 0], colours: [14'u8, 3, 4],
                       mapWidth: 3, mapHeight: 2)
  for i in 0..2:
    var c = Char(material: uint8(i + 1), colours: [uint8(8 + i), uint8(2 + i), uint8(5 + i)])
    for j in 0..7: c.data[j] = uint8(16 * i + j)
    result.chars.add c
  result.tiles = @[Tile(cells: @[0'u16, 1], colours: [9'u8, 3, 4], tag: 7, name: "floor"),
                   Tile(cells: @[2'u16, 0x123], colours: [10'u8, 5, 6], tag: 8, name: "say \"hi\""),
                   Tile(cells: @[0x345'u16, 2], colours: [11'u8, 7, 1], tag: 9)]
  result.map = @[0'u16, 1, 2, 2, 1, 0]

proc spriteProject(): SpriteProject =
  result = SpriteProject(version: 5, colours: [11'u8, 1, 0], tileSystem: true,
                         tileWidth: 2, tileHeight: 1)
  for i in 0..2:
    var s = Sprite(attributes: uint8(0x80 + i))
    for j in 0..62: s.data[j] = uint8(i)
    result.sprites.add s
  result.tiles = @[SpriteTile(cells: @[0'u16, 1], attributes: 0x10, tag: 4),
                   SpriteTile(cells: @[2'u16, 0], tag: 5)]
  result.spriteAnims = @[Animation(first: 0, last: 2, timer: 6, attributes: 0x10)]
  result.tileAnims = @[Animation(first: 0, last: 1, timer: 3)]

proc lines(s: string): seq[string] = s.splitLines

func opts(parts: seq[string] = @[], prefix = "", org: seq[(string, int)] = @[],
          stubs = false): AsmOptions =
  AsmOptions(parts: parts, prefix: prefix, org: org, eventStubs: stubs,
             bin: BinOptions(cells: cf16))

suite "CharPad C source":
  test "constants and arrays":
    let s = charProject().toC(opts()).source
    check "// Generated by batchpad, after the CharPad Pro template." in s
    for c in ["#define colr_vic_bg0 6", "#define char_count 3", "#define tile_wid 2",
              "#define map_hei_pxls 16", "#define size_charset_data 0x18 // (24 bytes)"]:
      check c in s.lines
    check "__export const unsigned char charset_data[] = {" in s.lines
    check "    0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17," in s.lines
    for l in s.splitLines:
      if l.startsWith("#define"): check "$" notin l

  test "parts, prefix and tile names":
    let s = charProject().toC(opts(@["tile-names", "map"], "lv_")).source
    check "__export const unsigned char lv_chartileset_names_data[] = {" in s.lines
    # "floor", then "say \"hi\"" at 6.
    check "    0x66,0x6c,0x6f,0x6f,0x72,0x00,0x73,0x61,0x79,0x20,0x22,0x68,0x69,0x22,0x00,0x00" in s.lines
    check "__export const unsigned char * const lv_chartileset_names[3] = {" in s.lines
    check "    &lv_chartileset_names_data[0], &lv_chartileset_names_data[6], &lv_chartileset_names_data[15]" in s.lines
    check "lv_map_data_lo[]" in s and "lv_map_data_hi[]" in s
    check "lv_charset_data" notin s

  test "tile events":
    var p = charProject()
    p.tiles[1].name = "say_hi"
    let s = p.toC(opts(@["tile-events"], stubs = true)).source
    check "void chtl_floor_event(void);" in s.lines
    check "void chtl_floor_event(void) {}" in s.lines
    check "__export void (* const chartileset_eventjumptable[3])(void) = {" in s.lines
    let none = p.toC(opts(@["tile-events"])).source
    check "{}" notin none

  test "header":
    let (source, header) = charProject().toC(opts(@["chars", "tile-names"], "lv_"), "level.h", "level.c")
    check "#ifndef BATCHPAD_LEVEL_H" in header.lines
    check "#pragma compile(\"level.c\")" in header.lines
    check "#define lv_char_count 3" in header.lines
    check "extern const unsigned char lv_charset_data[];" in header.lines
    check "extern const unsigned char * const lv_chartileset_names[3];" in header.lines
    check "#endif" in header.lines
    check "#include \"level.h\"" in source.lines
    check "#define" notin source
    check "__export const unsigned char lv_charset_data[] = {" in source.lines

  test "org places a part in a section of its own":
    let s = charProject().toC(opts(@["chars", "tiles", "map"], org = @[("chars", 0x2000), ("map", 0xc000)])).source
    check "#define addr_charset_data 0x2000" in s.lines
    check "#pragma section(sec_charset_data, 0)" in s.lines
    check "#pragma region(reg_charset_data, 0x2000, 0x2018, , , {sec_charset_data})" in s.lines
    check "#pragma data(sec_charset_data)" in s.lines
    # Both halves of the map are in the one region.
    check "#pragma region(reg_map_data_lo, 0xc000, 0xc00c, , , {sec_map_data_lo})" in s.lines
    check s.count("#pragma data(data)") == 2

  test "mistakes":
    let p = charProject()
    expect AsmError: discard p.toC(opts(prefix = "1x"))
    expect AsmError: discard p.toC(opts(@["chars"], prefix = "a-b"))
    expect AsmError: discard p.toC(opts(@["chars"], org = @[("map", 0x1000)]))
    expect AsmError: discard p.toC(opts(@["chars"], org = @[("chars", 0xfff8)]))
    expect AsmError: discard p.toC(opts(@["chars", "chars"]))
    expect AsmError: discard p.toC(opts(@["sprites"]))
    var q = p
    q.tiles[0].name = "int"
    expect AsmError: discard q.toC(opts(@["tile-events"], stubs = true))

