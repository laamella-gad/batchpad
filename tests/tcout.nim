suite "compiling":
  ## oscar64 is used when it is on the PATH, and left out otherwise.
  let dir = getTempDir() / "batchpad_tcout"
  setup: createDir(dir)
  teardown: removeDir(dir)

  test "oscar64 puts the parts at their addresses":
    if findExe("oscar64") == "":
      skip()
    else:
      let o = opts(@["chars", "tile-names"], "lv_", @[("chars", 0x2000), ("tile-names", 0x3000)])
      let (source, header) = charProject().toC(o, "level.h", "level.c")
      writeFile(dir / "level.c", source)
      writeFile(dir / "level.h", header)
      writeFile(dir / "main.c", "#include \"level.h\"\nint main(void) { return lv_char_count; }\n")
      let (output, code) = execCmdEx("cd " & quoteShell(dir) & " && oscar64 main.c -o=out.prg")
      check code == 0
      if code != 0: echo output
      else:
        # The program loads at $0801; the file has its address in front.
        let prg = readFile(dir / "out.prg")
        proc at(a, n: int): string = prg[2 + a - 0x801 ..< 2 + a - 0x801 + n]
        check at(0x2000, 8) == "\x00\x01\x02\x03\x04\x05\x06\x07"
        check "floor\x00" in at(0x3000, 0x10)
